import { config, requireValue } from "../config.js";
import { TestCase, UserStory } from "../types.js";
import { HttpError, basicAuth, http } from "../utils/http.js";
import { adfToText, extractAcceptanceCriteria } from "../utils/text.js";

function base(): string {
  return `${requireValue(config.jira.baseUrl, "JIRA_BASE_URL")}/rest/api/${config.jira.apiVersion}`;
}

function headers(): Record<string, string> {
  const token = requireValue(config.jira.apiToken, "JIRA_API_TOKEN");
  if (config.jira.authType === "bearer") return { Authorization: `Bearer ${token}` };
  return { Authorization: basicAuth(requireValue(config.jira.email, "JIRA_EMAIL"), token) };
}

const isV3 = () => config.jira.apiVersion === "3";
const fieldText = (v: any): string => (v == null ? "" : typeof v === "string" ? v : adfToText(v));

export async function readJiraStory(key: string): Promise<UserStory> {
  const acField = config.jira.acceptanceCriteriaField;
  const fields = ["summary", "description", "status", "labels", "issuetype", acField].filter(Boolean).join(",");
  const issue = await http<any>(`${base()}/issue/${encodeURIComponent(key)}?fields=${fields}`, { headers: headers() });
  const description = fieldText(issue.fields.description).trim();
  const acText = acField ? fieldText(issue.fields[acField]).trim() : "";
  // An Acceptance Criteria field holding only "-" / "N/A" is treated as empty -> parse the description instead
  const meaningful = acText.replace(/\b(n\/?a|none|tbd)\b/gi, "").replace(/[\W_]/g, "").length >= 5;
  let acceptanceCriteria = meaningful ? extractAcceptanceCriteria(`Acceptance Criteria:\n${acText}`) : [];
  if (!acceptanceCriteria.length) acceptanceCriteria = extractAcceptanceCriteria(description);
  return {
    tracker: "jira",
    id: issue.key,
    title: issue.fields.summary,
    description,
    acceptanceCriteria,
    status: issue.fields.status?.name,
    labels: issue.fields.labels ?? [],
    url: `${config.jira.baseUrl}/browse/${issue.key}`,
  };
}

// ---------- description builders ----------

function adfCell(text: string, header = false) {
  return {
    type: header ? "tableHeader" : "tableCell",
    content: [{ type: "paragraph", content: text ? [{ type: "text", text }] : [] }],
  };
}

function adfDescription(tc: TestCase, storyKey: string): any {
  const p = (text: string, strong = false) => ({
    type: "paragraph",
    content: [{ type: "text", text, ...(strong ? { marks: [{ type: "strong" }] } : {}) }],
  });
  const content: any[] = [];
  content.push(p(`Generated by QA MCP from user story ${storyKey}.`));
  if (tc.objective) content.push(p("Objective", true), p(tc.objective));
  if (tc.preconditions?.length) {
    content.push(p("Preconditions", true), {
      type: "bulletList",
      content: tc.preconditions.map((pc) => ({ type: "listItem", content: [p(pc)] })),
    });
  }
  content.push(p("Test Steps", true), {
    type: "table",
    content: [
      { type: "tableRow", content: ["#", "Action", "Test Data", "Expected Result"].map((h) => adfCell(h, true)) },
      ...tc.steps.map((s, i) => ({
        type: "tableRow",
        content: [String(i + 1), s.action, s.data ?? "", s.expected ?? ""].map((c) => adfCell(c)),
      })),
    ],
  });
  content.push(p(`Priority: ${tc.priority} | Type: ${tc.type}`));
  return { type: "doc", version: 1, content };
}

function wikiDescription(tc: TestCase, storyKey: string): string {
  const esc = (s = "") => s.replace(/\|/g, "\\|") || " ";
  const out = [`Generated by QA MCP from user story ${storyKey}.`, ""];
  if (tc.objective) out.push("*Objective*", tc.objective, "");
  if (tc.preconditions?.length) out.push("*Preconditions*", ...tc.preconditions.map((p) => `* ${p}`), "");
  out.push("*Test Steps*", "||#||Action||Test Data||Expected Result||");
  tc.steps.forEach((s, i) => out.push(`|${i + 1}|${esc(s.action)}|${esc(s.data)}|${esc(s.expected)}|`));
  out.push("", `Priority: ${tc.priority} | Type: ${tc.type}`);
  return out.join("\n");
}

// ---------- upload ----------

export async function uploadJiraTestCases(
  storyKey: string,
  testCases: TestCase[],
  projectKey?: string,
): Promise<TestCase[]> {
  const project = projectKey || config.jira.projectKey || storyKey.split("-")[0];
  let issueType = config.jira.testIssueType;
  const learned: Record<string, unknown> = {}; // required fields copied from the story, reused for every test case
  const results: TestCase[] = [];

  for (const tc of testCases) {
    const fields: any = {
      project: { key: project },
      summary: `[${storyKey}] ${tc.title}`.slice(0, 250),
      issuetype: { name: issueType },
      description: isV3() ? adfDescription(tc, storyKey) : wikiDescription(tc, storyKey),
      labels: ["qa-mcp", "auto-generated", `type-${tc.type.toLowerCase()}`, ...(tc.tags ?? [])].map((l) =>
        l.replace(/\s+/g, "-"),
      ),
    };
    Object.assign(fields, config.jira.extraFields, learned);
    const created = await createIssue(fields, storyKey, learned);
    issueType = fields.issuetype.name;
    try {
      await http(`${base()}/issueLink`, {
        method: "POST",
        headers: headers(),
        body: { type: { name: config.jira.linkType }, inwardIssue: { key: created.key }, outwardIssue: { key: storyKey } },
      });
    } catch (e) {
      console.error(`[qa-mcp] Could not link ${created.key} to ${storyKey}:`, (e as Error).message);
    }
    results.push({ ...tc, externalId: created.key, externalUrl: `${config.jira.baseUrl}/browse/${created.key}` });
  }
  return results;
}

/** Reduce a field value read from Jira to the shape Jira accepts on create (option -> {id}, user -> {accountId}). */
function toWritable(v: any): any {
  if (Array.isArray(v)) return v.map(toWritable);
  if (v && typeof v === "object") {
    if (v.accountId) return { accountId: v.accountId };
    if (v.id) return { id: String(v.id) };
    if (v.key) return { key: v.key };
    if (v.value) return { value: v.value };
  }
  return v;
}

/** Possible write formats for a value read from Jira, most likely first. */
function candidates(v: any): any[] {
  const out: any[] = [];
  const push = (x: any) => {
    if (x !== undefined && x !== null && !out.some((o) => JSON.stringify(o) === JSON.stringify(x))) out.push(x);
  };
  push(toWritable(v));
  if (v && typeof v === "object" && !Array.isArray(v)) {
    if (v.id) push(String(v.id)); // Atlassian Team field expects the plain id
    if (v.value) push({ value: v.value });
    if (v.name) push({ name: v.name });
  }
  if (Array.isArray(v)) push(v.map((x: any) => (x?.value ? { value: x.value } : toWritable(x))));
  push(v);
  return out;
}

/**
 * Create an issue. On HTTP 400 it adapts and retries:
 *  - unknown issue type  -> fall back to JIRA_FALLBACK_ISSUE_TYPE
 *  - required custom fields (e.g. "Squad is required") -> copy their values from the parent story,
 *    trying the different value formats Jira uses for select / team / user fields
 */
async function createIssue(fields: any, storyKey: string, learned: Record<string, unknown>): Promise<any> {
  const options: Record<string, any[]> = {};
  let lastError: unknown;
  for (let attempt = 0; attempt < 10; attempt++) {
    try {
      const created = await http<any>(`${base()}/issue`, { method: "POST", headers: headers(), body: { fields } });
      for (const k of Object.keys(options)) learned[k] = fields[k];
      return created;
    } catch (e) {
      lastError = e;
      if (!(e instanceof HttpError && e.status === 400)) throw e;
      let errs: Record<string, string> = {};
      try {
        errs = JSON.parse(e.responseText).errors ?? {};
      } catch {
        throw e;
      }
      if (errs.issuetype && fields.issuetype?.name !== config.jira.fallbackIssueType) {
        fields.issuetype = { name: config.jira.fallbackIssueType };
        continue;
      }
      const failing = Object.keys(errs).filter((k) => k.startsWith("customfield_"));
      if (!failing.length) throw e;
      const unknown = failing.filter((k) => !(k in options));
      if (unknown.length) {
        const story = await http<any>(`${base()}/issue/${encodeURIComponent(storyKey)}?fields=${unknown.join(",")}`, { headers: headers() });
        const noValue: string[] = [];
        for (const k of unknown) {
          const v = story.fields?.[k];
          if (v === null || v === undefined || (Array.isArray(v) && !v.length)) noValue.push(`${k} (${errs[k]})`);
          else options[k] = candidates(v);
        }
        if (noValue.length)
          throw new Error(
            `[qa-mcp v1.1] Jira requires ${noValue.join(", ")} and story ${storyKey} has no value to copy. ` +
              `Set it in .env, e.g. JIRA_EXTRA_FIELDS={"${noValue[0].split(" ")[0]}":{"value":"Your option"}}`,
          );
      }
      // move each failing field to its next candidate format
      let progressed = false;
      for (const k of failing) {
        const next = options[k]?.shift();
        if (next !== undefined) {
          fields[k] = next;
          progressed = true;
        }
      }
      if (!progressed) {
        throw new Error(
          `[qa-mcp v1.1] Jira still rejects ${failing.join(", ")} after copying the value from ${storyKey} in every known format. ` +
            `Last response: ${e.responseText.slice(0, 400)}. Set the value explicitly with JIRA_EXTRA_FIELDS in .env.`,
        );
      }
    }
  }
  throw lastError instanceof Error ? lastError : new Error("Could not create the Jira issue.");
}
