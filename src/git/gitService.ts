import fs from "node:fs";
import path from "node:path";
import { simpleGit } from "simple-git";
import { config, requireValue } from "../config.js";
import { HttpError, basicAuth, http } from "../utils/http.js";
import { azHttp, azProjectSegment } from "../integrations/azureDevOps.js";

export type GitProvider = "github" | "azure";

export interface PushOptions {
  projectDir: string;
  provider: GitProvider;
  repoName: string;
  branch?: string;
  commitMessage: string;
  /** GitHub owner (user or org). Defaults to GITHUB_OWNER or the token's user. */
  owner?: string;
  /** Azure DevOps project that hosts the repo. Defaults to AZDO_PROJECT. */
  azureProject?: string;
  createRepoIfMissing?: boolean;
  privateRepo?: boolean;
}

export interface PushResult {
  remoteUrl: string;
  branch: string;
  commit: string;
  createdRepo: boolean;
  webUrl: string;
}

async function ensureGithubRepo(o: PushOptions): Promise<{ owner: string; clone: string; web: string; created: boolean }> {
  const token = requireValue(config.github.token, "GITHUB_TOKEN");
  const h = { Authorization: `Bearer ${token}`, "X-GitHub-Api-Version": "2022-11-28", "User-Agent": "qa-mcp" };
  let owner = o.owner || config.github.owner;
  if (!owner) owner = (await http<any>(`${config.github.apiUrl}/user`, { headers: h })).login;
  try {
    const repo = await http<any>(`${config.github.apiUrl}/repos/${owner}/${o.repoName}`, { headers: h });
    return { owner, clone: repo.clone_url, web: repo.html_url, created: false };
  } catch (e) {
    if (!(e instanceof HttpError && e.status === 404) || o.createRepoIfMissing === false) throw e;
  }
  const me = (await http<any>(`${config.github.apiUrl}/user`, { headers: h })).login;
  const endpoint = me.toLowerCase() === owner.toLowerCase() ? `${config.github.apiUrl}/user/repos` : `${config.github.apiUrl}/orgs/${owner}/repos`;
  const repo = await http<any>(endpoint, {
    method: "POST",
    headers: h,
    body: { name: o.repoName, private: o.privateRepo ?? true, description: "UI automation generated by QA MCP", auto_init: false },
  });
  return { owner, clone: repo.clone_url, web: repo.html_url, created: true };
}

async function ensureAzureRepo(o: PushOptions): Promise<{ clone: string; web: string; created: boolean }> {
  const org = requireValue(config.azure.orgUrl, "AZDO_ORG_URL").replace(/\/+$/, "");
  const project = o.azureProject || requireValue(config.azure.project, "AZDO_PROJECT");
  const h = { Authorization: basicAuth("", requireValue(config.azure.pat, "AZDO_PAT")) };
  const api = `${org}/${azProjectSegment(project)}/_apis/git/repositories`;
  try {
    const repo = await azHttp<any>(`${api}/${encodeURIComponent(o.repoName)}?api-version=${config.azure.apiVersion}`, { headers: h });
    return { clone: repo.remoteUrl, web: repo.webUrl, created: false };
  } catch (e) {
    if (!(e instanceof HttpError && e.status === 404) || o.createRepoIfMissing === false) throw e;
  }
  const proj = await azHttp<any>(`${org}/_apis/projects/${azProjectSegment(project)}?api-version=${config.azure.apiVersion}`, { headers: h });
  const repo = await azHttp<any>(`${api}?api-version=${config.azure.apiVersion}`, {
    method: "POST",
    headers: h,
    body: { name: o.repoName, project: { id: proj.id } },
  });
  return { clone: repo.remoteUrl, web: repo.webUrl, created: true };
}

/** Insert credentials into an https clone URL for a one-off push (never stored in .git/config). */
function authUrl(clone: string, provider: GitProvider): string {
  const u = new URL(clone);
  if (provider === "github") {
    u.username = "x-access-token";
    u.password = requireValue(config.github.token, "GITHUB_TOKEN");
  } else {
    u.username = "qa-mcp";
    u.password = requireValue(config.azure.pat, "AZDO_PAT");
  }
  return u.toString();
}

export async function commitAndPush(o: PushOptions): Promise<PushResult> {
  if (!fs.existsSync(o.projectDir)) throw new Error(`Project folder not found: ${o.projectDir}`);
  const branch = o.branch || config.git.defaultBranch;
  const repo =
    o.provider === "github"
      ? await ensureGithubRepo(o)
      : await ensureAzureRepo(o);

  const git = simpleGit({ baseDir: o.projectDir });
  if (!fs.existsSync(path.join(o.projectDir, ".git"))) {
    await git.init();
  }
  await git.addConfig("user.name", config.git.authorName);
  await git.addConfig("user.email", config.git.authorEmail);
  await git.addConfig("core.autocrlf", "input");

  const remotes = await git.getRemotes(true);
  if (remotes.find((r) => r.name === "origin")) await git.remote(["set-url", "origin", repo.clone]);
  else await git.addRemote("origin", repo.clone);

  // check out branch (create if needed)
  const local = await git.branchLocal();
  if (local.current !== branch) {
    if (local.all.includes(branch)) await git.checkout(branch);
    else await git.checkout(["-B", branch]);
  }

  await git.add(["-A"]);
  const status = await git.status();
  let commit = (await git.revparse(["HEAD"]).catch(() => "")) as string;
  if (status.files.length) {
    const res = await git.commit(o.commitMessage);
    commit = res.commit || (await git.revparse(["HEAD"]));
  }
  if (!commit) throw new Error("Nothing to commit and no previous commit exists.");

  // If the remote branch exists with history we don't have, rebase onto it first.
  const pushUrl = authUrl(repo.clone, o.provider);
  try {
    await git.push(pushUrl, `HEAD:refs/heads/${branch}`);
  } catch (e) {
    const msg = String((e as Error).message);
    if (/rejected|fetch first|non-fast-forward/i.test(msg)) {
      await git.pull(pushUrl, branch, { "--rebase": "true" });
      await git.push(pushUrl, `HEAD:refs/heads/${branch}`);
    } else throw new Error(msg.replace(/\/\/[^@\s]+@/g, "//***@"));
  }
  await git.fetch("origin").catch(() => undefined);

  return {
    remoteUrl: repo.clone,
    branch,
    commit: (await git.revparse(["HEAD"])).trim(),
    createdRepo: repo.created,
    webUrl: repo.web,
  };
}
