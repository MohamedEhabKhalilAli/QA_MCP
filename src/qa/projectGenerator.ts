function readme(o: GenerateProjectOptions): string {
  return `# ${o.projectName}

UI automation for **${o.story.id} — ${o.story.title}**, generated by QA MCP.

Stack: Playwright · TypeScript · Page Object Model · Allure 3

## Structure
\`\`\`
pages/          Page objects (BasePage + one class per screen)
fixtures/       Playwright fixtures that inject page objects into tests
tests/          Specs generated from the test cases
data/           Test data (edit testData.json — replace CHANGE_ME values)
locators/       Raw locator detection output
utils/          Shared assertions + pending-step helper
\`\`\`

## Run
\`\`\`bash
npm install
npx playwright install chromium
npm test                 # run all tests
npm run report:generate  # build Allure report into ./allure-report
npm run report:open      # open it
\`\`\`
Set \`BASE_URL\` to target another environment.

Steps that could not be mapped to a locator call \`pendingStep()\`; those tests show as **fixme** in the report
until you implement the step in the page object.
`;
}
