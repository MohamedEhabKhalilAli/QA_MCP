const severityOf = (tc: TestCase) => (tc.priority === "High" ? "critical" : tc.priority === "Medium" ? "normal" : "minor");

function specFile(o: GenerateProjectOptions): { content: string; automated: number; pending: { testCase: string; items: string[] }[] } {
  const ctx = { pages: o.pages, entryPage: fx(o.pages[0]) };
  let automated = 0;
  const pendingAll: { testCase: string; items: string[] }[] = [];
  let needsData = false;
  let needsHelpers = false;

  const tests = o.testCases.map((tc) => {
    const used = new Set<string>(["page"]);
    const bodies: string[] = [];
    const pending: string[] = [];
    // make sure every test starts on a page
    const steps = [...tc.steps];
    const needsLogin = (tc.preconditions ?? []).some((p) => /\b(logged|signed)\s+in\b|\bauthenticated\b/i.test(p));
    const login = needsLogin ? loginCode(ctx) : undefined;
    if (login) {
      used.add(login.pageFx);
      needsData = true;
      bodies.push(`    await test.step('Precondition: user is logged in', async () => {\n${login.code.map((l) => "      " + l).join("\n")}\n    });`);
    }
    const firstIsNav = steps[0] && /\b(navigate|open|go to|visit|launch|page under test|is on)\b/i.test(steps[0].action);
    if (!firstIsNav && !login) steps.unshift({ action: `Open the ${o.pages[0].pageName.replace(/Page$/, "")} page` });

    steps.forEach((s, i) => {
      const t = translateStep(ctx, s, i);
      t.usedPages.forEach((u) => used.add(u));
      if (t.usedPages.has("testData")) needsData = true;
      if (t.usedPages.has("helpers")) needsHelpers = true;
      automated += t.code.length ? 1 : 0;
      pending.push(...t.pending);
      const lines = [...t.code, ...t.pending.map((p) => `await pendingStep(${q(p)});`)];
      if (s.expected) lines.unshift(`// Expected: ${s.expected.replace(/\n/g, " ")}`);
      bodies.push(`    await test.step(${q(t.title)}, async () => {\n${lines.map((l) => "      " + l).join("\n")}\n    });`);
    });
    if (pending.length) pendingAll.push({ testCase: `${tc.id} ${tc.title}`, items: pending });

    const fixtureArgs = [...used].filter((u) => u !== "testData" && u !== "helpers");
    const tags = [`@${o.story.id}`, `@${tc.type.toLowerCase()}`, `@${tc.priority.toLowerCase()}`, ...(tc.tags ?? []).map((t) => "@" + toKebab(t))];
    const meta = [
      `await allure.epic(${q(o.projectName)});`,
      `await allure.feature(${q(`${o.story.id}: ${o.story.title}`)});`,
      `await allure.story(${q(tc.sourceCriterion?.split("\n")[0] ?? o.story.title)});`,
      `await allure.severity(${q(severityOf(tc))});`,
      o.story.url ? `await allure.issue(${q(o.story.url)}, ${q(o.story.id)});` : "",
      tc.externalUrl ? `await allure.tms(${q(tc.externalUrl)}, ${q(tc.externalId ?? tc.id)});` : "",
      tc.objective ? `await allure.description(${q(tc.objective)});` : "",
    ].filter(Boolean);

    return `  test(${q(`${tc.id}${tc.externalId ? ` [${tc.externalId}]` : ""}: ${tc.title}`)}, { tag: [${[...new Set(tags)].map(q).join(", ")}] }, async ({ ${fixtureArgs.join(", ")} }) => {
${meta.map((m) => "    " + m).join("\n")}
${tc.preconditions?.length ? tc.preconditions.map((p) => `    // Precondition: ${p}`).join("\n") + "\n" : ""}${bodies.join("\n")}
  });`;
  });

  const content = `import * as allure from 'allure-js-commons';
import { test, expect } from '../fixtures/pages';
import { pendingStep } from '../utils/pending';
${needsHelpers ? "import { expectAnyErrorMessage } from '../utils/assertions';\n" : ""}${needsData ? "import testData from '../data/testData.json';\n" : ""}
/**
 * ${o.story.id}: ${o.story.title}
 * ${o.story.url ?? ""}
 * Generated by QA MCP from ${o.testCases.length} test case(s).
 * Steps marked with pendingStep() could not be mapped to a detected locator — implement them in the page object.
 */
test.describe(${q(`${o.story.id}: ${o.story.title}`)}, () => {
${tests.join("\n\n")}
});

// keep 'expect' referenced even if no assertion was generated
void expect;
`;
  return { content, automated, pending: pendingAll };
}

