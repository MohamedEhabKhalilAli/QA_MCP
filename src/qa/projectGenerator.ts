function pagePath(url: string, baseUrl: string): string {
  try {
    const u = new URL(url);
    const b = new URL(baseUrl);
    if (u.origin === b.origin) {
      const basePath = b.pathname.replace(/\/$/, "");
      const rel = u.pathname.startsWith(basePath) ? u.pathname.slice(basePath.length) : u.pathname;
      return (rel || "/") + u.search;
    }
  } catch {
    /* fall through */
  }
  return url;
}

function pageObject(p: PageLocators, baseUrl: string): string {
  const fields = p.locators.map((l) => `  /** ${l.description} — strategy: ${l.strategy}${l.css ? ` | css: ${l.css}` : ""} */\n  readonly ${l.key}: Locator;`);
  const inits = p.locators.map((l) => `    this.${l.key} = ${l.playwright};`);
  const methods = p.locators.map((l) => method(l)).filter(Boolean);
  const visible = p.locators.filter((l) => !["message"].includes(l.elementType)).map((l) => `this.${l.key}`);
  return `import { Locator, Page } from '@playwright/test';
import { BasePage } from './BasePage';

/**
 * Page Object: ${p.pageName}
 * Source URL: ${p.url}${p.title ? `\n * Title: ${p.title}` : ""}
 * Generated by QA MCP — locators were verified to resolve to exactly one element.
 */
export class ${p.pageName} extends BasePage {
  readonly path = ${q(pagePath(p.url, baseUrl))};

${fields.join("\n\n")}

  constructor(page: Page) {
    super(page);
${inits.join("\n")}
  }

  /** Elements expected to be visible when the page is loaded */
  protected elements(): Locator[] {
    return [${visible.join(", ")}];
  }

${methods.join("\n\n")}
}
`;
}

function method(l: LocatorEntry): string {
  const name = methodNameFor(l);
  const doc = `  /** ${l.description} */\n`;
  switch (l.elementType) {
    case "input":
    case "textarea":
      return `${doc}  async ${name}(value: string): Promise<void> {\n    await this.fill(this.${l.key}, value);\n  }`;
    case "select":
      return `${doc}  async ${name}(option: string): Promise<void> {\n    await this.select(this.${l.key}, option);\n  }`;
    case "checkbox":
    case "radio":
      return `${doc}  async ${name}(checked = true): Promise<void> {\n    await this.setChecked(this.${l.key}, checked);\n  }`;
    case "heading":
    case "message":
      return `${doc}  async ${name}(): Promise<string> {\n    return this.textOf(this.${l.key});\n  }`;
    default:
      return `${doc}  async ${name}(): Promise<void> {\n    await this.click(this.${l.key});\n  }`;
  }
}

function fixtures(pages: PageLocators[]): string {
  return `import { test as base } from '@playwright/test';
${pages.map((p) => `import { ${p.pageName} } from '../pages/${p.pageName}';`).join("\n")}

/** Page objects injected into every test (Page Object Model + Playwright fixtures). */
export type PageFixtures = {
${pages.map((p) => `  ${fx(p)}: ${p.pageName};`).join("\n")}
};

export const test = base.extend<PageFixtures>({
${pages.map((p) => `  ${fx(p)}: async ({ page }, use) => {\n    await use(new ${p.pageName}(page));\n  },`).join("\n")}
});

export { expect } from '@playwright/test';
`;
}

function mergeTestData(existing: any, pages: PageLocators[], creds?: { username: string; password: string }): any {
  const out: any = { ...existing };
  for (const p of pages) {
    const key = fx(p);
    out[key] = out[key] ?? {};
    for (const l of p.locators) {
      if (!["input", "textarea"].includes(l.elementType)) continue;
      out[key][l.key] = out[key][l.key] ?? defaultData(l);
      if (creds && /pass/i.test(l.key)) out[key][l.key].valid = creds.password;
      else if (creds && /user|email|login/i.test(l.key)) out[key][l.key].valid = creds.username;
    }
  }
  return out;
}

function defaultData(l: LocatorEntry): { valid: string; invalid: string } {
  const k = `${l.key} ${l.description}`.toLowerCase();
  if (/mail/.test(k)) return { valid: "qa.user@example.com", invalid: "invalid-email@" };
  if (/pass/.test(k)) return { valid: "CHANGE_ME_valid_password", invalid: "wrong_password_123" };
  if (/user|login/.test(k)) return { valid: "CHANGE_ME_valid_username", invalid: "invalid_user_123" };
  if (/phone|mobile|tel/.test(k)) return { valid: "+201000000000", invalid: "abc" };
  if (/zip|postal/.test(k)) return { valid: "12345", invalid: "ABCDE" };
  if (/search/.test(k)) return { valid: "test", invalid: "@@@###" };
  return { valid: "Test value", invalid: "!!invalid!!" };
}

