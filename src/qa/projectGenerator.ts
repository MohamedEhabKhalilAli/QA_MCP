const BASE_PAGE = `import { expect, Locator, Page } from '@playwright/test';

/**
 * BasePage — common behaviour shared by every page object (Page Object Model).
 * Child pages declare their locators as readonly fields and expose intent-revealing methods.
 */
export abstract class BasePage {
  /** Path relative to baseURL (or an absolute URL) */
  abstract readonly path: string;

  constructor(readonly page: Page) {}

  /** Elements expected on screen once the page has loaded */
  protected abstract elements(): Locator[];

  async open(): Promise<void> {
    await this.page.goto(this.path);
    await this.waitForReady();
  }

  async waitForReady(): Promise<void> {
    await this.page.waitForLoadState('domcontentloaded');
  }

  async expectLoaded(): Promise<void> {
    await expect(this.page).toHaveURL(this.urlPattern());
  }

  async expectAllElementsVisible(): Promise<void> {
    for (const el of this.elements()) await expect(el).toBeVisible();
  }

  async expectText(text: string): Promise<void> {
    await expect(this.page.getByText(text).first()).toBeVisible();
  }

  async title(): Promise<string> {
    return this.page.title();
  }

  // ---------- protected helpers used by child pages ----------
  protected async fill(locator: Locator, value: string): Promise<void> {
    await locator.waitFor({ state: 'visible' });
    await locator.fill(value);
  }

  protected async click(locator: Locator): Promise<void> {
    await locator.waitFor({ state: 'visible' });
    await locator.click();
  }

  protected async select(locator: Locator, option: string): Promise<void> {
    await locator.selectOption({ label: option }).catch(() => locator.selectOption(option));
  }

  protected async setChecked(locator: Locator, checked: boolean): Promise<void> {
    await locator.setChecked(checked);
  }

  protected async textOf(locator: Locator): Promise<string> {
    return (await locator.innerText()).trim();
  }

  private urlPattern(): RegExp {
    const p = this.path.split('?')[0];
    if (p === '/' || p === '') return /.*/;
    return new RegExp(p.replace(/[.*+?^\${}()|[\\]\\\\]/g, '\\\\$&') + '/?(\\\\?.*)?(#.*)?$');
  }
}
`;

const ASSERTIONS = `import { expect, Page } from '@playwright/test';

/** Generic check that some error / validation feedback is shown to the user. */
export async function expectAnyErrorMessage(page: Page): Promise<void> {
  const candidates = page
    .getByRole('alert')
    .or(page.locator('[class*="error" i]:visible, [class*="invalid" i]:visible, [class*="flash" i]:visible, [aria-invalid="true"]'));
  await expect(candidates.first()).toBeVisible();
}
`;

const PENDING = `import { test } from '@playwright/test';
import * as allure from 'allure-js-commons';

/**
 * A test step that QA MCP could not map to a detected locator.
 * By default the test is marked "fixme" (skipped with a reason) so the report never shows a false pass.
 * Set ALLOW_PENDING_STEPS=true to just log it and keep going.
 */
export async function pendingStep(description: string): Promise<void> {
  test.info().annotations.push({ type: 'pending-step', description });
  await allure.label('pending-step', description);
  if (process.env.ALLOW_PENDING_STEPS !== 'true') {
    test.fixme(true, \`Step not automated yet: \${description}\`);
  }
}
`;

