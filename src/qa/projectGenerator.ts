export interface GenerateProjectOptions {
  projectDir: string;
  projectName: string;
  baseUrl: string;
  story: UserStory;
  testCases: TestCase[];
  pages: PageLocators[];
  /** When false, never overwrite existing page objects (spec + data are still merged/updated). */
  overwritePages?: boolean;
  singleFileReport?: boolean;
  /** Valid credentials written into data/testData.json for username/email + password fields */
  credentials?: { username: string; password: string };
}

export interface GenerateProjectResult {
  projectDir: string;
  files: string[];
  automatedSteps: number;
  pendingSteps: { testCase: string; items: string[] }[];
}

const fx = (p: PageLocators) => toCamelCase(p.pageName);

export function generateProject(o: GenerateProjectOptions): GenerateProjectResult {
  if (!o.pages.length) throw new Error("No page locators supplied. Run detect_locators first.");
  const files: string[] = [];
  const put = (rel: string, content: string, overwrite = true) => {
    const abs = path.join(o.projectDir, rel);
    if (!overwrite && fs.existsSync(abs)) return;
    writeFile(abs, content);
    files.push(rel);
  };

  // ---------- static scaffolding ----------
  put("package.json", packageJson(o.projectName), false);
  put("tsconfig.json", TSCONFIG, false);
  put("playwright.config.ts", playwrightConfig(o.baseUrl), false);
  put("allurerc.mjs", allureRc(o.projectName, o.singleFileReport ?? false), false);
  put(".gitignore", GITIGNORE, false);
  put(".env.example", `BASE_URL=${o.baseUrl}\nHEADLESS=true\n# Set to true to let tests with not-yet-automated steps run instead of being marked fixme\nALLOW_PENDING_STEPS=false\n`, false);
  put("pages/BasePage.ts", BASE_PAGE);
  put("utils/assertions.ts", ASSERTIONS);
  put("utils/pending.ts", PENDING);
  put(".github/workflows/playwright.yml", GITHUB_WORKFLOW, false);
  put("azure-pipelines.yml", AZURE_PIPELINE, false);

  // ---------- page objects ----------
  for (const p of o.pages) put(`pages/${p.pageName}.ts`, pageObject(p, o.baseUrl), o.overwritePages ?? true);
  put("pages/index.ts", o.pages.map((p) => `export { ${p.pageName} } from './${p.pageName}';`).join("\n") + "\nexport { BasePage } from './BasePage';\n");
  put("fixtures/pages.ts", fixtures(o.pages));
  put("locators/locators.json", JSON.stringify(o.pages, null, 2));

  // ---------- test data (merge with existing so user edits survive) ----------
  const dataFile = path.join(o.projectDir, "data/testData.json");
  const existing = fs.existsSync(dataFile) ? JSON.parse(fs.readFileSync(dataFile, "utf8")) : {};
  put("data/testData.json", JSON.stringify(mergeTestData(existing, o.pages, o.credentials), null, 2));

  // ---------- spec ----------
  const spec = specFile(o);
  put(`tests/${toKebab(o.story.id)}.spec.ts`, spec.content);
  put("README.md", readme(o), false);

  return { projectDir: o.projectDir, files, automatedSteps: spec.automated, pendingSteps: spec.pending };
}

